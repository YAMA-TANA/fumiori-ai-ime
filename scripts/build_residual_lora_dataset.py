def build_dataset(target_count: int = 70000) -> Path:
    samples: List[Dict[str, Any]] = []
    default_domain = "一般的な日本語文書として、文脈に即した自然で正確な表記を優先する。"

    print("Generating targeted residual disambiguation pairs across failure families...")
    # 1. Homophone families (Balanced polarities)
    for fam in HOMOPHONE_FAMILIES:
        reading = fam["reading"]
        for group in fam["groups"]:
            pos_word = group["word"]
            negs = group["negs"]
            templates = group["templates"]
            for prefix, suffix in templates:
                query = (
                    f"文書方針: {default_domain}\n"
                    f"文脈「{prefix}____{suffix}」に最も適切な表記を選びなさい。"
                )
                pos_text = f"{prefix}{pos_word}{suffix}"
                for neg in negs:
                    # A few broad dictionaries include the positive spelling
                    # itself; never emit an identical pair because it teaches
                    # the ranker an impossible ordering.
                    if neg == pos_word:
                        continue
                    neg_text = f"{prefix}{neg}{suffix}"
                    if neg_text == pos_text:
                        continue
                    # Hard negative repeats to enforce clear decision boundary
                    repeat = 60 if ("はな" in reading or "はし" in reading or "あめ" in reading or "かみ" in reading or "くも" in reading or "しよう" in reading or "ほしょう" in reading or "はっこう" in reading or "かいてい" in reading or "けっさい" in reading or "しょうがい" in reading) else 35
                    for _ in range(repeat):
                        samples.append({
                            "reading": reading,
                            "query": query,
                            "positive": pos_text,
                            "negative": neg_text,
                        })

    print(f"  Generated {len(samples):,} homophone balance pairs.")

    # 2. Natural Hiragana protection pairs
    hiragana_samples = []
    for item in NATURAL_HIRAGANA_CASES:
        query = (
            f"文書方針: {default_domain}\n"
            f"文脈「{item['prefix']}____{item['suffix']}」に最も適切な表記を選びなさい。"
        )
        pos_text = f"{item['prefix']}{item['pos']}{item['suffix']}"
        for neg in item["negs"]:
            neg_text = f"{item['prefix']}{neg}{item['suffix']}"
            for _ in range(50):
                hiragana_samples.append({
                    "reading": item["reading"],
                    "query": query,
                    "positive": pos_text,
                    "negative": neg_text,
                })
    print(f"  Generated {len(hiragana_samples):,} natural hiragana protection pairs.")
    samples.extend(hiragana_samples)

    # 3. Success replay from existing high-quality dataset
    base_data_path = ROOT / "integration" / "ime_combined_stress_train_30k.json"
    if base_data_path.exists():
        base_samples = json.loads(base_data_path.read_text(encoding="utf-8"))
        # Sample replay pairs to preserve general Japanese knowledge (about 25-30% of target)
        replay_size = min(len(base_samples), int(target_count * 0.25))
        random.seed(42)
        replay_samples = random.sample(base_samples, replay_size)
        print(f"  Sampled {len(replay_samples):,} general Japanese replay pairs.")
        samples.extend(replay_samples)

    # 4. Natural-context homophone pairs collected from JMdict + Tatoeba.
    # This shard is generated by scripts/collect_comprehensive_homophone_data.py
    # and is deliberately capped so one public corpus cannot dominate the
    # curated residual examples above.
    corpus_path = ROOT / "data" / "homophone_sources" / "tatoeba_homophone_pairs.jsonl"
    if corpus_path.exists():
        corpus_samples = []
        for line in corpus_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if all(row.get(key) for key in ("reading", "query", "positive", "negative")):
                corpus_samples.append(row)
        random.seed(20260909)
        corpus_cap = min(len(corpus_samples), 30000)
        if len(corpus_samples) > corpus_cap:
            corpus_samples = random.sample(corpus_samples, corpus_cap)
        print(f"  Added {len(corpus_samples):,} natural-context JMdict/Tatoeba homophone pairs.")
        samples.extend(corpus_samples)

    # Shuffle dataset
    random.seed(42)
    random.shuffle(samples)

    print(f"Total residual training pairs: {len(samples):,}")

    out_path = ROOT / "integration" / "ime_residual_lora_train.json"
    out_path.write_text(json.dumps(samples, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[SUCCESS] Residual dataset written to {out_path} ({out_path.stat().st_size / (1024*1024):.2f} MB)")
    return out_path


if __name__ == "__main__":
    build_dataset()
