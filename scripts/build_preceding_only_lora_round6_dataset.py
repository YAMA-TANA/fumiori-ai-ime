def _load_known_strings() -> Set[str]:
    known: Set[str] = set()
    output_path = ROOT / "integration" / "ime_residual_lora_round6_preceding_only.json"
    for path in (ROOT / "integration").glob("*.json"):
        # The output is intentionally allowed to be regenerated.  Treating a
        # previous round6 shard as holdout input would make a second run drop
        # all fresh rows and leave only replay data.
        if path == output_path:
            continue
        rows = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(rows, list):
            for row in rows:
                if isinstance(row, dict):
                    for key in ("positive", "negative", "query", "text", "prompt"):
                        value = row.get(key)
                        if isinstance(value, str):
                            known.add(value)
    holdout = ROOT / "build" / "preceding_only_range_holdout_evaluation.json"
    if holdout.exists():
        data = json.loads(holdout.read_text(encoding="utf-8"))
        for row in data.get("details", []):
            known.add(str(row.get("prefix", "")) + str(row.get("expected", "")))
    return known


def _append_pair(rows: List[Dict[str, Any]], known: Set[str], reading: str, query: str, prefix: str, pos: str, neg: str, source: str) -> None:
    positive = prefix + pos
    negative = prefix + neg
    if pos == neg or positive == negative or positive in known or negative in known:
        return
    rows.append({"reading": reading, "query": query, "positive": positive, "negative": negative, "source": source})


def build() -> Path:
    known = _load_known_strings()
    rows: List[Dict[str, Any]] = []
    domain = "前文脈だけで判断し、助詞・活用・実務分野に合う自然で正確な表記を選ぶ。"
    for reading, positive, negatives, templates in FAMILIES:
        for prefix, particle in templates:
            query = f"文書方針: {domain}\n前文脈「{prefix}____」の変換候補を選びなさい。"
            for negative in negatives:
                for _ in range(24):
                    _append_pair(rows, known, reading, query, prefix, positive, negative, "preceding-only-lexical")
                pquery = f"文書方針: {domain}\n前文脈「{prefix}____」の助詞込み変換候補を選びなさい。"
                for _ in range(24):
                    _append_pair(rows, known, reading + particle, pquery, prefix, positive + particle, negative + particle, "preceding-only-particle")

    for reading, prefix, positive, candidates in WIDE_PHRASES:
        query = f"文書方針: {domain}\n前文脈「{prefix}____」の長い一セグメントを選びなさい。"
        for negative in candidates:
            if negative == positive:
                continue
            for _ in range(50):
                _append_pair(rows, known, reading, query, prefix, positive, negative, "preceding-only-wide")

    # Replay general pairs to reduce catastrophic forgetting while keeping the
    # new preceding-only distribution dominant.
    base = ROOT / "integration" / "ime_residual_lora_train.json"
    if base.exists():
        general = json.loads(base.read_text(encoding="utf-8"))
        random.seed(20260915)
        rows.extend(random.sample(general, min(12000, len(general))))
    random.seed(20260915)
    random.shuffle(rows)
    out = ROOT / "integration" / "ime_residual_lora_round6_preceding_only.json"
    out.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"round6 preceding-only pairs: {len(rows):,} -> {out}")
    print("fresh target rows:", sum(1 for row in rows if str(row.get("source", "")).startswith("preceding-only")))
    return out


if __name__ == "__main__":
    build()
